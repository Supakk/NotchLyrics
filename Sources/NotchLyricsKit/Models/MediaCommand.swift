    case pause = 1
    case togglePlayPause = 2
    case stop = 3
    case nextTrack = 4
    case previousTrack = 5
    case advanceRepeat = 6
    case advanceShuffle = 7
    case toggleMute = 8
    case advancePlaybackMode = 9
}
